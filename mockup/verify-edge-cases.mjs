  const context=vm.createContext({document:{querySelector:node,querySelectorAll:()=>[],hidden:false,activeElement:node('active'),addEventListener:(name,fn)=>{const previous=events.get(name);events.set(name,previous?event=>Promise.all([previous(event),fn(event)]):fn)}},location:{hash},window:{addEventListener(){},scrollTo(){},confirm(){status.confirms++;return options.confirm!==false},location:{reload(){status.reloads++}}},localStorage:{getItem:key=>values.get(key)??null,setItem:(key,value)=>{if(key===failOnce){failOnce=null;throw Error('Storage full')}values.set(key,value)},removeItem:key=>values.delete(key)},performance:{now:()=>1000},crypto:{randomUUID:()=>String(Math.random())},requestAnimationFrame:()=>1,cancelAnimationFrame(){},setTimeout:()=>1,clearTimeout(){},console,Date,Intl,Math,Set});
